/* bin2c: turn a binary file into a C array, so game data can be compiled into
 * the program.
 *
 *   bin2c <input> <output.c> <symbol>
 *
 * Writes `const unsigned char <symbol>[]` and `const unsigned <symbol>_len`.
 */
#include <stdio.h>

int main(int argc, char **argv){
    FILE *in, *out; int c; unsigned long n = 0;
    if (argc != 4){ fprintf(stderr, "usage: bin2c <input> <output.c> <symbol>\n"); return 2; }
    if (!(in = fopen(argv[1], "rb"))){ perror(argv[1]); return 1; }
    if (!(out = fopen(argv[2], "w"))){ perror(argv[2]); return 1; }
    fprintf(out, "/* Generated by tools/bin2c.c from %s -- do not edit. */\n", argv[1]);
    fprintf(out, "const unsigned char %s[] = {\n", argv[3]);
    while ((c = fgetc(in)) != EOF){
        fprintf(out, "%u,", (unsigned)c);
        if (++n % 32 == 0) fputc('\n', out);
    }
    fprintf(out, "0};\nconst unsigned %s_len = %lu;\n", argv[3], n);
    fclose(in); fclose(out);
    return 0;
}
