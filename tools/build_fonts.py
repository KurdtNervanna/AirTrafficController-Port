"""Compile the pixel-art fonts in fonts/*.txt into src/fonts_builtin.c.

    python tools/build_fonts.py

Each font becomes a classic Mac 'FONT' resource (the same layout the System file
uses), so the game's font code draws it unchanged. Advance widths are checked
against the metrics of the fonts they stand in for, so text lays out on exactly
the same pixels.
"""
import os, re, struct, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONTS = ['tower12.txt', 'radar9.txt', 'radar12.txt']

# advance widths of the fonts being stood in for (layout compatibility)
CHICAGO12 = dict(zip(
    ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~',
    [4, 6, 7, 10, 7, 11, 10, 3, 5, 5, 7, 7, 4, 7, 4, 7] + [8] * 10 + [4, 4, 6, 8, 6, 8, 11] +
    [8, 8, 8, 8, 7, 7, 8, 8, 6, 7, 9, 7, 12, 9, 8, 8, 8, 8, 7, 6, 8, 8, 12, 8, 8, 8] +
    [5, 7, 5, 8, 8, 6] +
    [8, 8, 7, 8, 8, 6, 8, 8, 4, 6, 8, 4, 12, 8, 8, 8, 8, 6, 7, 6, 8, 8, 12, 8, 8, 8] +
    [5, 5, 5, 8]))
CHICAGO12.update({'\x11': 11, '\x12': 11, '\x13': 9, '\x14': 11, '\xb0': 14, '\xc6': 9})
EXPECTED = {12: CHICAGO12, 521: 6, 524: 7}


def parse(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    hdr, glyphs, i = None, {}, 0
    while i < len(lines):
        ln = lines[i].rstrip()
        if ln.startswith('font '):
            hdr = dict(kv.split('=') for kv in ln.split()[1:])
            for k in ('id', 'ascent', 'descent', 'leading', 'top', 'rows'):
                hdr[k] = int(hdr[k])
        elif ln.startswith('char '):
            tok = ln[5:].strip()
            ch = chr(int(tok, 16)) if tok.startswith('0x') else tok
            if len(ch) != 1:
                sys.exit(f'{path}:{i+1}: bad char {tok!r}')
            rows = [r.rstrip() for r in lines[i + 1:i + 1 + hdr['rows']]]
            if len(rows) != hdr['rows'] or len({len(r) for r in rows}) != 1 or any(set(r) - set('.#') for r in rows):
                sys.exit(f'{path}:{i+1}: glyph {tok!r} must be {hdr["rows"]} equal rows of . and #')
            glyphs[ch] = rows
            i += hdr['rows']
        i += 1
    return hdr, glyphs


def derive(glyph9):
    """Scale a Radar 9 glyph (10 rows x 6) to the Radar 12 grid (13 rows x 7)."""
    rmap = [0, 1, 2, 2, 3, 4, 5, 5, 6, 7, 8, 8, 9]
    cmap = [0, 1, 2, 2, 3, 4, 5]
    return [''.join(glyph9[r][c] for c in cmap) for r in rmap]


def build(hdr, glyphs):
    fid, asc, desc, lead, top = hdr['id'], hdr['ascent'], hdr['descent'], hdr['leading'], hdr['top']
    height = asc + desc
    exp = EXPECTED[fid]
    for ch, rows in glyphs.items():
        want = exp if isinstance(exp, int) else exp.get(ch)
        if want is not None and len(rows[0]) != want:
            sys.exit(f'font {fid}: {ch!r} is {len(rows[0])} wide, expected {want}')
    missing_w = (exp if isinstance(exp, int) else 8)
    mrows = ['.' * missing_w] * hdr['rows']
    box = ['#' * (missing_w - 1) + '.' if r in (1, 9) else ('#' + '.' * (missing_w - 3) + '#.' if 1 < r < 9 else '.' * missing_w)
           for r in range(hdr['rows'])]
    first, last = 0, 255
    order = [chr(c) for c in range(first, last + 1)]
    # strike: all glyphs side by side, then the missing-character box
    cols, loc, ow = [], [], []
    x = 0
    for ch in order + [None]:
        rows = box if ch is None else glyphs.get(ch)
        loc.append(x)
        if rows is None:
            ow.append(0xFFFF)
            continue
        w = len(rows[0])
        cols.append((x, rows))
        ow.append(w)                      # offset 0 (kernMax 0), width w
        x += w
    loc.append(x)
    ow.append(0xFFFF)
    row_words = (x + 15) // 16
    bits = bytearray(row_words * 2 * height)
    for x0, rows in cols:
        for r, line in enumerate(rows):
            y = top + r
            for c, p in enumerate(line):
                if p == '#':
                    xx = x0 + c
                    bits[y * row_words * 2 + xx // 8] |= 0x80 >> (xx % 8)
    widmax = max(len(r[0]) for _, r in cols)
    n = last - first + 3
    owtloc = (26 + len(bits) + n * 2 - 16) // 2      # words from the owTLoc field to the table
    head = struct.pack('>13h', -28672, first, last, widmax, 0, -desc, widmax, height, owtloc, asc, desc, lead, row_words)
    data = head + bytes(bits) + struct.pack(f'>{n}H', *loc) + struct.pack(f'>{n}H', *ow)
    return data


def main():
    out = ['/* Generated by tools/build_fonts.py from fonts/*.txt -- do not edit. */',
           '/* Original bitmap fonts drawn for this project (MIT licence), in classic Mac FONT format. */',
           '#include <stddef.h>', '']
    table = []
    parsed = {name: parse(os.path.join(ROOT, 'fonts', name)) for name in FONTS}
    for name in FONTS:
        hdr, glyphs = parsed[name]
        if 'derive' in hdr:
            _, src = parsed[hdr['derive']]
            for ch, rows in src.items():
                glyphs.setdefault(ch, derive(rows))
        data = build(hdr, glyphs)
        sym = 'font_' + re.sub(r'\W', '_', name.split('.')[0])
        out.append(f'static const unsigned char {sym}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            out.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
        out.append('};')
        table.append((hdr['id'], sym, len(data)))
        print(f'{name}: FONT {hdr["id"]}, {len(glyphs)} glyphs, {len(data)} bytes')
    out += ['', '/* the built-in FONT resource with this id, or NULL */',
            'const unsigned char *font_builtin(int id, unsigned *len){',
            '    switch (id){']
    for fid, sym, n in table:
        out.append(f'    case {fid}: *len = {n}; return {sym};')
    out += ['    }', '    return NULL;', '}', '']
    open(os.path.join(ROOT, 'src', 'fonts_builtin.c'), 'w', newline='\n').write('\n'.join(out))
    print('wrote src/fonts_builtin.c')


if __name__ == '__main__':
    main()
